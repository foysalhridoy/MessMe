/**
 * Checks if a message string consists exclusively of 1 to 4 emojis (for enlarged rendering)
 */
export function isOnlyEmojis(text: string): boolean {
  if (!text) return false;
  const trimmed = text.trim();
  // Regex matches emoji sequences
  const emojiRegex = /^(\p{Extended_Pictographic}|\p{Emoji_Presentation}|\uFE0F|\u200D|\s){1,10}$/u;
  if (!emojiRegex.test(trimmed)) return false;
  // Count actual characters without spaces
  const clean = trimmed.replace(/\s+/g, '');
  return clean.length >= 1 && clean.length <= 16;
}
